#!/usr/bin/env python3
"""Generate chatbot/certs.h containing the root CAs used by api.deepseek.com.

api.deepseek.com is served by Amazon CloudFront:
    *.deepseek.com  <-  Amazon RSA 2048 M01  <-  Amazon Root CA 1
The served chain also carries a Starfield Services Root CA G2 cross-signed
copy of Amazon Root CA 1, so both roots are embedded to keep mbedTLS chain
building happy.  Run this script only if the roots need refreshing.
"""
from __future__ import annotations

import os
import socket
import ssl
import tempfile
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
CERT_DIR = os.path.join(HERE, "certs")
OUT = os.path.join(os.path.dirname(HERE), "chatbot", "certs.h")

AMAZON_URL = "https://www.amazontrust.com/repository/AmazonRootCA1.pem"
STARFIELD_NAME = "Starfield Services Root Certificate Authority - G2"
AMAZON_NAME = "Amazon Root CA 1"


def http_get(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=60).read().decode("ascii", "replace")


def flatten(seq):
    out = {}
    for rdn in seq:
        if isinstance(rdn[0], tuple):
            for name, value in rdn:
                out[name] = value
        elif len(rdn) == 2 and isinstance(rdn[0], str):
            out[rdn[0]] = rdn[1]
    return out


def decode(der: bytes):
    pem = ssl.DER_cert_to_PEM_cert(der)
    fd, path = tempfile.mkstemp(suffix=".pem")
    os.close(fd)
    with open(path, "w", encoding="ascii") as f:
        f.write(pem)
    try:
        info = ssl._ssl._test_decode_cert(path)
    finally:
        os.unlink(path)
    return pem, flatten(info["subject"]), flatten(info["issuer"])


def roots_from_chain():
    """Return {common name: PEM} for the roots in the live DeepSeek chain."""
    ctx = ssl.create_default_context()
    with socket.create_connection(("api.deepseek.com", 443), timeout=20) as s:
        with ctx.wrap_socket(s, server_hostname="api.deepseek.com") as ss:
            chain = ss.get_verified_chain()
    found = {}
    for der in chain:
        pem, subject, issuer = decode(der)
        if subject == issuer:  # self-signed root
            found[subject.get("commonName", "")] = pem
    return found


def c_string(pem: str) -> str:
    lines = pem.strip().splitlines()
    return "\n".join('"%s\\n"' % line for line in lines)


def main() -> int:
    os.makedirs(CERT_DIR, exist_ok=True)
    amazon = None
    starfield = None

    try:
        amazon = http_get(AMAZON_URL)
        print("downloaded Amazon Root CA 1")
    except Exception as exc:  # noqa: BLE001
        print(f"download failed ({exc}), will use the live chain")

    chain_roots = roots_from_chain()
    if amazon is None:
        amazon = chain_roots.get(AMAZON_NAME)
    starfield = chain_roots.get(STARFIELD_NAME)

    if not amazon or not starfield:
        print("ERROR: could not obtain both root certificates")
        return 1

    with open(os.path.join(CERT_DIR, "AmazonRootCA1.pem"), "w", encoding="ascii", newline="\n") as f:
        f.write(amazon.strip() + "\n")
    with open(os.path.join(CERT_DIR, "StarfieldG2.pem"), "w", encoding="ascii", newline="\n") as f:
        f.write(starfield.strip() + "\n")

    body = (
        "// AUTO-GENERATED by tools/gen_certs.py - do not edit.\n"
        "// Root CAs for api.deepseek.com (Amazon CloudFront / Amazon Trust Services).\n"
        "#pragma once\n\n"
        "static const char ROOT_CA_PEM[] =\n"
        + c_string(amazon)
        + "\n"
        + c_string(starfield)
        + ";\n"
    )
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(body)
    print(f"wrote {OUT} ({len(body)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
