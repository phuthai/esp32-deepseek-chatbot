#!/usr/bin/env python3
"""Generate chatbot/generated_info.h from info.txt.

Run automatically by build.bat / build.ps1 before compiling.  Everything the
user puts in info.txt is turned into C string/int literals that get compiled
into the firmware, so the final .bin already contains the API key, Wi-Fi
credentials and system role.

Handles UTF-8 (with or without BOM) and falls back to GBK for files saved by
Chinese Windows editors.
"""
from __future__ import annotations

import datetime
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
INFO = os.path.join(ROOT, "info.txt")
OUT = os.path.join(ROOT, "chatbot", "generated_info.h")

DEFAULTS = {
    "WIFI_SSID": "",
    "WIFI_PASS": "",
    "API_KEY": "",
    "SYSTEM_ROLE": "You are a helpful assistant.",
    "MODEL": "deepseek-chat",
    "MAX_TOKENS": "512",
    "TEMPERATURE": "0.7",
    "HISTORY_CHARS": "8000",
    "STREAM": "1",
}


def read_text(path: str) -> str:
    raw = open(path, "rb").read()
    for enc in ("utf-8-sig", "gbk"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("utf-8", "replace")


def parse(text: str) -> dict:
    values = {}
    for lineno, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#") or s.startswith(";"):
            continue
        if "=" not in s:
            print(f"  ! line {lineno}: ignored (no '='): {s[:60]}")
            continue
        key, val = s.split("=", 1)
        key = key.strip().upper()
        val = val.strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        val = val.replace("\\n", "\n").replace("\\t", "\t")
        values[key] = val
    return values


def c_escape(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def main() -> int:
    if not os.path.exists(INFO):
        example = INFO + ".example"
        if os.path.exists(example):
            shutil.copyfile(example, INFO)
            print("  info.txt was missing - created it from info.txt.example")
        else:
            print(f"ERROR: {INFO} not found")
            return 1

    cfg = dict(DEFAULTS)
    cfg.update(parse(read_text(INFO)))

    problems = []
    if not cfg["WIFI_SSID"] or cfg["WIFI_SSID"] in ("YourWiFiName",):
        problems.append("WIFI_SSID is not set")
    if not cfg["API_KEY"] or cfg["API_KEY"].startswith("sk-xxx"):
        problems.append("API_KEY is not set (chat will fail until you add it)")
    if cfg["MODEL"] not in ("deepseek-chat", "deepseek-reasoner"):
        print(f"  ! MODEL='{cfg['MODEL']}' - expected deepseek-chat or deepseek-reasoner")

    def as_int(name: str) -> int:
        try:
            return int(float(cfg[name]))
        except (ValueError, KeyError):
            print(f"  ! {name}='{cfg[name]}' is not a number, using {DEFAULTS[name]}")
            return int(DEFAULTS[name])

    def as_float(name: str) -> float:
        try:
            return float(cfg[name])
        except (ValueError, KeyError):
            print(f"  ! {name}='{cfg[name]}' is not a number, using {DEFAULTS[name]}")
            return float(DEFAULTS[name])

    max_tokens = max(16, min(8192, as_int("MAX_TOKENS")))
    temperature = max(0.0, min(2.0, as_float("TEMPERATURE")))
    history_chars = max(0, as_int("HISTORY_CHARS"))
    stream = 1 if str(cfg["STREAM"]).strip().lower() not in ("0", "off", "false", "no") else 0

    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")

    lines = [
        "// AUTO-GENERATED by tools/gen_info.py from info.txt - do not edit.",
        "// Change info.txt and rebuild instead.",
        "#pragma once",
        "",
        f'#define CFG_WIFI_SSID "{c_escape(cfg["WIFI_SSID"])}"',
        f'#define CFG_WIFI_PASS "{c_escape(cfg["WIFI_PASS"])}"',
        f'#define CFG_API_KEY "{c_escape(cfg["API_KEY"])}"',
        f'#define CFG_SYSTEM_ROLE "{c_escape(cfg["SYSTEM_ROLE"])}"',
        f'#define CFG_MODEL "{c_escape(cfg["MODEL"])}"',
        f"#define CFG_MAX_TOKENS {max_tokens}",
        f"#define CFG_TEMPERATURE {temperature}f",
        f"#define CFG_HISTORY_CHARS {history_chars}",
        f"#define CFG_STREAM {stream}",
        f'#define CFG_BUILD_STAMP "{stamp}"',
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"  config -> {os.path.relpath(OUT, ROOT)}")
    print(f"  Wi-Fi  : {cfg['WIFI_SSID'] or '(not set)'}")
    print(f"  API key: {cfg['API_KEY'][:5]}...{cfg['API_KEY'][-4:] if len(cfg['API_KEY']) > 9 else '****'}")
    print(f"  Model  : {cfg['MODEL']}, stream={stream}, max_tokens={max_tokens}, temp={temperature}")
    role = cfg["SYSTEM_ROLE"].replace("\n", " ")
    print(f"  Role   : {role[:70]}{'...' if len(role) > 70 else ''}")
    for p in problems:
        print(f"  WARNING: {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
